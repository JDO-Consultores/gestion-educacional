using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;

namespace GestionColegios.ViewModels
{
    // ??????????????????????????????????????????????????????????????????????
    // Formulario crear / editar apoderado
    // ??????????????????????????????????????????????????????????????????????
    public class ApoderadoViewModel
    {
        public int ID { get; set; }

        // --- Identificación ---
        [Required] public string Rut { get; set; }
        [Required] public string Nombres { get; set; }
        [Required] public string ApellidoPaterno { get; set; }
        public string ApellidoMaterno { get; set; }
        public int? NacionalidadID { get; set; }
        public string Nacionalidad { get; set; }

        // --- Datos laborales y educacionales ---
        public int? NivelEducacionalID { get; set; }
        public string NivelEducacional { get; set; }
        public int? SituacionLaboralID { get; set; }
        public string SituacionLaboral { get; set; }
        public string LugarTrabajo { get; set; }

        // --- Contacto ---
        public string Direccion { get; set; }
        public int? RegionID { get; set; }
        public int? ComunaID { get; set; }
        public string Comuna { get; set; }
        public string Region { get; set; }
        public string Telefono { get; set; }
        public string TelefonoCelular { get; set; }

        [EmailAddress]
        public string Email { get; set; }

        // --- Nombre completo (solo lectura) ---
        public string NombreCompleto =>
            $"{ApellidoPaterno} {ApellidoMaterno}, {Nombres}".Trim(',', ' ');
    }

    // ??????????????????????????????????????????????????????????????????????
    // Formulario de asociación alumno ? apoderado
    // ??????????????????????????????????????????????????????????????????????
    public class ApoderadoFormViewModel
    {
        public int AlumnoID { get; set; }
        public string AlumnoNombreCompleto { get; set; }
        public string AlumnoRut { get; set; }

        /// <summary>null = nuevo apoderado / >0 = asociar apoderado existente</summary>
        public ApoderadoViewModel Apoderado { get; set; } = new ApoderadoViewModel();

        public int ParentescoID { get; set; }
        public bool EsApoderadoTitular { get; set; }

        /// <summary>Padre | Madre | Apoderado</summary>
        public string TipoApoderado { get; set; } = "Apoderado";

        public List<SelectItemViewModel> Parentescos { get; set; } = new List<SelectItemViewModel>();
    }
}
